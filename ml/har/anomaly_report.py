"""Build results/anomaly.md and results/anomaly_curve.png from the routine-deviation runs.

    python -m har.anomaly_report
"""

from __future__ import annotations

import json

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import pandas as pd  # noqa: E402

from .anomaly_inject import DRIFT_DAYS, DRIFT_STEP_MIN, TYPES  # noqa: E402
from .data import DATASETS  # noqa: E402
from .run import RESULTS_DIR  # noqa: E402

SHORT = {"gt": "Annotations", "seg": "Segment GB", "win": "Live BiLSTM"}
METHOD = {"routine": "Routine model (ours)", "generic": "Generic AD (autoencoder)"}
TYPE = {"missed": "Missed", "prolonged": "Prolonged", "unusual_time": "Unusual time",
        "night_frequency": "Night toilet trips", "inactivity": "Inactivity"}


def pct(x) -> str:
    return "–" if x is None or x != x else f"{100 * x:.0f}"


def main():
    lines = [
        "# Routine-deviation detection results", "",
        "Generated by `python -m har.anomaly_report` from `<home>/anomaly/`. Protocol: decisions "
        "D12–D14 in `paper/decisions.md`; code: `har/run_anomaly.py`, `har/anomaly.py`.", "",
        "Synthetic routine deviations are injected into the **raw sensor events** of the "
        "monitoring days (last 20 % of days). Each resident's routine is learned from the "
        "observation period (middle 20 %) of the same activity stream; recognisers are trained "
        "on the first 60 %. Thresholds are calibrated on the observation period to **0.1 alerts "
        "per normal day per routine aspect** (operating point below).", "",
        "*Detection* = share of injected deviations matched by an alert. *F1* = day-level, per "
        "type, on a balanced set of injected and clean days, averaged over types. *False alerts* "
        "= alerts per clean monitoring day (on Milan these are Christmas-holiday days, so many are "
        f"real routine changes). *Drift* = {DRIFT_DAYS}-day runs in which the first cooking "
        f"episode moves {DRIFT_STEP_MIN} min later each day; detected = drift alert naming "
        "cooking within the run.", ""]
    fig, axes = plt.subplots(1, 2, figsize=(10, 4), sharey=True)
    for ax, ds in zip(axes, DATASETS):
        f = RESULTS_DIR / ds / "anomaly" / "summary.json"
        if not f.exists():
            continue
        S = json.loads(f.read_text())
        inj = pd.read_csv(RESULTS_DIR / ds / "anomaly" / "injections.csv")
        n_inj = inj[~inj["kind"].isin(["clean", "drift"])]["kind"].value_counts()
        n_runs = inj.loc[inj["kind"] == "drift", "seq"].nunique()
        lines += [f"## {ds.capitalize()}", "",
                  f"{S['n_observation_days']} observation days, {S['n_monitoring_days']} "
                  f"monitoring days, {int(n_inj.sum())} injected single-day copies ("
                  + ", ".join(f"{TYPE[t]} {n_inj.get(t, 0)}" for t in TYPES)
                  + f") and {n_runs} drift runs.", ""]
        if S.get("har"):
            lines += ["Recognition quality on the clean monitoring days (vs annotations): "
                      + "; ".join(f"{SHORT[k]} macro-F1 {100 * v['macro_f1']:.1f}, accuracy "
                                  f"{100 * v['accuracy']:.1f}" for k, v in S["har"].items()) + ".",
                      ""]
        lines += ["| Activity stream | Detector | " + " | ".join(TYPE[t] for t in TYPES)
                  + " | Mean detection | F1 | False alerts / day | Drift runs detected "
                  "(drift false alerts / day) |",
                  "|---|---|" + "---|" * (len(TYPES) + 4)]
        for key, r in S["results"].items():
            stream, method = key.split("/")
            dr = r.get("drift")
            lines.append(f"| {SHORT[stream]} | {METHOD[method]} | "
                         + " | ".join(pct(r["types"].get(t, {}).get("detection_rate"))
                                      for t in TYPES)
                         + f" | **{pct(r['mean_detection_rate'])}** | {pct(r['macro_f1'])} | "
                         f"{r['false_alerts_per_day']:.2f} | "
                         + (f"{dr['detected']} / {dr['runs']} ({dr['false_alerts_per_day']:.2f})"
                            if dr else "–") + " |")
        lines += ["", "Median detection delay, routine model (minutes after the deviation "
                  "starts; drift: days into the run):", "",
                  "| Activity stream | " + " | ".join(TYPE[t] for t in TYPES) + " | Drift |",
                  "|---|" + "---|" * (len(TYPES) + 1)]
        for key, r in S["results"].items():
            stream, method = key.split("/")
            if method != "routine":
                continue
            dr = r.get("drift") or {}
            lines.append(f"| {SHORT[stream]} | " + " | ".join(
                "–" if r["types"].get(t, {}).get("median_delay_min") is None
                else f"{r['types'][t]['median_delay_min']:.0f}" for t in TYPES)
                + f" | {dr.get('median_delay_days') if dr.get('median_delay_days') else '–'} |")
        al = RESULTS_DIR / ds / "anomaly" / "alerts_gt_routine.csv"
        if al.exists():
            a = pd.read_csv(al)
            c = a[a["day_kind"] == "clean"]["kind"].value_counts()
            lines += ["", "Alerts on clean monitoring days by routine aspect (annotations stream): "
                      + ", ".join(f"{k} {v}" for k, v in c.items()) + "."]
        sw = pd.read_csv(RESULTS_DIR / ds / "anomaly" / "sweep.csv")
        st = sw[sw["method"] == "routine"]
        lines += ["", "Matched false-alert comparison: the generic baseline at its most sensitive "
                  "setting (budget 1) vs the routine model's best detection at no more false "
                  "alerts per clean day.", "",
                  "| Activity stream | Generic AD: detection @ false alerts/day | "
                  "Routine model: detection @ false alerts/day |", "|---|---|---|"]
        for s_ in sw["stream"].unique():
            g = sw[(sw["stream"] == s_) & (sw["method"] == "generic")].sort_values("budget").iloc[-1]
            r = st[(st["stream"] == s_) & (st["false_alerts_per_day"] <= g["false_alerts_per_day"])]
            rt = (f"{100 * r['mean_detection_rate'].max():.0f} % @ "
                  f"{r.loc[r['mean_detection_rate'].idxmax(), 'false_alerts_per_day']:.2f}"
                  if len(r) else "no setting this quiet")
            lines.append(f"| {SHORT[s_]} | {100 * g['mean_detection_rate']:.0f} % @ "
                         f"{g['false_alerts_per_day']:.2f} | {rt} |")
        lines += ["", "Budget sweep, routine model: mean detection % / false alerts per clean day.",
                  "", "| Budget per aspect | " + " | ".join(SHORT[s] for s in st["stream"].unique())
                  + " |", "|---|" + "---|" * st["stream"].nunique()]
        for b in sorted(st["budget"].unique()):
            row = [f"| {b:g} "]
            for s in st["stream"].unique():
                r = st[(st["stream"] == s) & (st["budget"] == b)].iloc[0]
                row.append(f" {100 * r['mean_detection_rate']:.0f} / "
                           f"{r['false_alerts_per_day']:.2f} ")
            lines.append("|".join(row) + "|")
        lines.append("")
        for (s, m), r in sw.groupby(["stream", "method"]):
            r = r.sort_values("false_alerts_per_day")
            ax.plot(r["false_alerts_per_day"], 100 * r["mean_detection_rate"],
                    "o-" if m == "routine" else "x--", label=f"{SHORT[s]} · {METHOD[m]}")
        ax.set_title(ds.capitalize())
        ax.set_xlabel("False alerts per clean day")
        ax.grid(alpha=0.3)
    axes[0].set_ylabel("Injected routine deviations detected (%)")
    axes[1].legend(fontsize=7)
    fig.tight_layout()
    fig.savefig(RESULTS_DIR / "anomaly_curve.png", dpi=150)
    lines += ["![Detection vs false alerts](anomaly_curve.png)", ""]
    (RESULTS_DIR / "anomaly.md").write_text("\n".join(lines), encoding="utf8")
    print("wrote", RESULTS_DIR / "anomaly.md")


if __name__ == "__main__":
    main()
